"""Pick the best seed-0 hillclimb config among the candidates and write the 3B job list (2 seeds)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CANDS = {  # run name -> overrides on configs/hc_best.yaml
    "hcD3_mlp_N5_T7": "model.N=5 model.arch_layout=[m4,[T7],m4]",
    "hcE1_mlp_N4_T5": "model.N=4 model.arch_layout=[m4,[T5],m4]",
    "hcE2_mlp_N3_T4": "model.N=3 model.arch_layout=[m4,[T4],m4]",
}
res = {}
for n in CANDS:
    p = ROOT / "runs" / n / "summary.json"
    if p.exists():
        res[n] = json.load(open(p))["val/bpb"]
best = min(res, key=res.get)
print("candidates:", res, "-> best:", best)
common = "configs/hc_best.yaml group=Final-3B train.total_bytes=3e9 train.eval_every=2000"
lines = [f"# auto-generated by scripts/launch_final.py: best 0.6B config = {best} ({res[best]:.4f})"]
for seed in (0, 1):
    lines.append(f"python -m latents.train {common} name=f3_{best[2:]}_s{seed} train.seed={seed} {CANDS[best]}")
(ROOT / "scripts" / "final_3B.txt").write_text("\n".join(lines) + "\n")
print(open(ROOT / "scripts" / "final_3B.txt").read())
